def generate_2_2_cycles(max_element):
    itertool_list = [list(p) for p in itertools.permutations(range(1, max_element + 1), 4)]
    output_list = []

    for p in itertool_list:
        perm = Permutation([p[:2], p[2:]])
        if not list_contains_item(output_list, perm):
            output_list.append(perm)

    return output_list


