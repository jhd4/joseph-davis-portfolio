from permutation_group_library.permutation import Permutation
from permutation_group_library.permutation_group import Permutation_Group
import itertools


def list_contains_item(input_list, item):
    for a in input_list:
        if a == item:
            return True
    return False


def generate_single_cycle_permutations_of_shape(max_element, element_count):
    itertool_list = [list(p) for p in itertools.permutations(range(1, max_element + 1), element_count)]
    output_list = []

    for p in itertool_list:
        perm = Permutation([p])
        if not list_contains_item(output_list, perm):
            output_list.append(perm)

    return output_list

